
using Microsoft.AspNetCore.Identity.Data;
using SchoolProject.Core.Features.Users.Commands.Models;
using SchoolProject.Data.Entities.Identity;
using SchoolProject.Data.Entities.Views;



namespace SchoolProject.Core.Mapping.Users
{
    public partial class UserProfile
    {
        public void AddUserMapping()
        {
            CreateMap<AddUserCommand,User>()
                .ForMember(dest => dest.UserName, opt => opt.MapFrom(src => src.UserName))
                .ForMember(dest => dest.Email, opt => opt.MapFrom(src => src.Email))
                .ForMember(dest => dest.Address, opt => opt.MapFrom(src => src.Address))
                .ForMember(dest => dest.FullName, opt => opt.MapFrom(src => src.FullNameEN))
                .ForMember(dest => dest.PhoneNumber, opt => opt.MapFrom(src => src.PhoneNumber));

            CreateMap<User, Student>()
                .ForMember(dest => dest.NameEN, opt => opt.MapFrom(src => src.FullName))
                .ForMember(dest => dest.Address, opt => opt.MapFrom(src => src.Address))
                .ForMember(dest => dest.Phone, opt => opt.MapFrom(src => src.PhoneNumber))
                .ForMember(dest => dest.UserId, opt => opt.Ignore()) // هتحط الـ UserId بعد إنشاء اليوزر
                .ForMember(dest => dest.StudID, opt => opt.Ignore()); // Auto-generated by DB

            CreateMap<User, Instructor>()
                .ForMember(dest => dest.ENameEn, opt => opt.MapFrom(src => src.FullName))
                .ForMember(dest => dest.Address, opt => opt.MapFrom(src => src.Address))
                .ForMember(dest => dest.Email, opt => opt.MapFrom(src => src.Email))
                .ForMember(dest => dest.UserId, opt => opt.Ignore()) // هتحط الـ UserId بعد إنشاء اليوزر
                .ForMember(dest => dest.InsId, opt => opt.Ignore()); // Auto-generated by DB


        }
    }
}
